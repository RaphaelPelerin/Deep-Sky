/**
 * Messages exchanged between the main-thread controller and the render engine.
 * The engine runs in a Web Worker when possible, so everything here must be structured-cloneable.
 */

/** linear RGB-ish color as 0..1 floats (sRGB values, no conversion) */
export type RGB = [number, number, number];
export type RGBA = [number, number, number, number];

export interface EnginePalette {
  background: RGB;
  nebula: [RGB, RGB, RGB, RGB];
  aurora: [RGB, RGB];
  rays: RGB;
  glow: RGB;
  stars: [RGB, RGB, RGB];
  spotlight: [RGB, RGB];
  lines: RGB;
  meteor: RGB;
  grid: RGBA;
}

export type EngineClick = 'shockwave' | 'ring' | 'none';

/** fully resolved and clamped settings: 0 disables a layer */
export interface EngineConfig {
  palettes: { dark: EnginePalette; light: EnginePalette };
  speed: number;
  intro: boolean;
  nebula: number;
  nebulaScale: number;
  shimmer: number;
  aurora: number;
  auroraPosition: number;
  rays: number;
  raysSpread: number;
  glow: number;
  lens: number;
  grain: number;
  vignette: number;
  stars: number;
  starSize: number;
  twinkle: number;
  parallax: number;
  flares: boolean;
  starSpeed: number;
  meteors: number;
  spotlight: number;
  spotlightRadius: number;
  field: number;
  fieldRadius: number;
  constellations: boolean;
  linkDistance: number;
  /** perspective floor: opacity (0 = off), cell size in px, scroll speed, height (0..1), tilt in degrees */
  grid: number;
  gridSize: number;
  gridSpeed: number;
  gridHeight: number;
  gridTilt: number;
  models: EngineModel[];
  click: EngineClick;
  scale: number;
  minScale: number;
  fps: number;
  adaptive: boolean;
}

/** surfaces, by shader id */
export const MATERIALS = ['auto', 'chrome', 'glass', 'hologram', 'iridescent', 'wire', 'nebula'] as const;
/** built-in shapes, generated by the 3D layer */
export const SHAPES = ['orb', 'knot', 'torus', 'crystal', 'gem', 'planet', 'cube'] as const;

/** one model of the scene, resolved and clamped (angles in radians) */
export interface EngineModel {
  /** asset id: `shape:<name>` for built-in shapes, else loaded through a `modelData` message */
  key: string;
  material: number;
  color: RGB | null;
  x: number;
  y: number;
  size: number;
  rotation: [number, number, number];
  spin: number;
  float: number;
  follow: number;
  react: number;
  morph: number;
  glow: number;
  rays: number;
  opacity: number;
  /** 0 hidden (dissolved) .. 1 fully there; the model animates towards it */
  reveal: number;
}

/** a glTF file, fetched on the main thread: JSON, buffers and images (structured-cloneable) */
export interface ModelAsset {
  gltf: Record<string, unknown>;
  buffers: ArrayBuffer[];
  images: ({ data: ArrayBuffer; type: string } | null)[];
}

/** what the model layer needs from the sky on every frame */
export interface ModelFrame {
  time: number;
  clock: number;
  /** light position, 0..1 with y up (follows the cursor, wanders otherwise) */
  light: [number, number];
  ripples: Float32Array;
  sweepAt: number;
  palette: EnginePalette;
  /** 0 light theme .. 1 dark theme */
  dark: number;
  /** brightness of the roaming light */
  glow: number;
  animated: boolean;
}

/** the 3D layer, loaded on demand (see src/models) */
export interface ModelLayerApi {
  /** true when something is (or will be) drawn: the engine then renders at full rate */
  readonly active: boolean;
  /** called when a model finished loading (a still frame then needs a redraw) */
  onChange?: () => void;
  configure(models: EngineModel[]): void;
  load(key: string, asset: ModelAsset): void;
  resize(w: number, h: number, dpr: number): void;
  /** the latest shader frame, refracted and reflected by the models */
  backdrop(source: TexImageSource): void;
  render(frame: ModelFrame): void;
  destroy(): void;
}

export interface EngineInit {
  config: EngineConfig;
  dark: boolean;
  animated: boolean;
  stats: boolean;
}

/** controller → engine */
export type EngineMessage =
  | ({ type: 'init'; gl: OffscreenCanvas; fx: OffscreenCanvas } & EngineInit)
  | { type: 'config'; config: EngineConfig }
  | { type: 'resize'; w: number; h: number; dpr: number }
  | { type: 'pointer'; x: number; y: number; inside: boolean }
  | { type: 'click'; x: number; y: number; effect?: 'shockwave' | 'ring' }
  | { type: 'pulse' }
  | { type: 'theme'; dark: boolean }
  | { type: 'animated'; on: boolean }
  | { type: 'visible'; on: boolean }
  /** the page's main thread is busy (long task): back off for a moment */
  | { type: 'busy' }
  | { type: 'stats'; on: boolean }
  /** worker only: start the 3D layer, from its script (main thread: Engine.attachModels) */
  | { type: 'modelsInit'; canvas: OffscreenCanvas; code: string }
  | { type: 'modelData'; key: string; asset: ModelAsset };

export interface EngineStats {
  /** particle layer frames per second */
  fps: number;
  /** shader frames per second */
  shaderFps: number;
  /** shader resolution, relative to CSS pixels */
  scale: number;
  particles: number;
}

/** engine → controller */
export type EngineEvent =
  | { type: 'boot' }
  | { type: 'ready' }
  | { type: 'glFailed' }
  | { type: 'modelError'; key: string; message: string }
  | ({ type: 'stats' } & EngineStats);
